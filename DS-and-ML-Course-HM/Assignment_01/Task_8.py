a = 5
b = 4
# Arithmetic operators: +, -, *, /, %, //, **
print(a+b) # Add a and b
print(a-b) # subtract b form a
print(a*b) # multiply a with b
print(a/b) # a divide b
print(a%b) # modulus (reminder)
print(a//b)# Floor division 
print(a**b)# a square b
#  Comparison operators: ==, !=, <, >, <= , >=

print(a==b) # Is a equal b (True or False)
print(a!=b) # Is not equal b (True or False)
print(a<b)  # Is a les than b (True or False)
print(a>b)  # is a greater than b (True or False)
print(a<=b) # is a less than or equal to b (True or False)
print(a>=b) # is a greater than or equal to b (True or False)

